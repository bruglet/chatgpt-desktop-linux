#!/usr/bin/env python3
"""Render a self-contained cask. No install-time code comes from a moving tap."""

import json
from pathlib import Path
import sys


def render(release):
    version = release["version"]
    revision = release["revision"]
    payload = release["payload"]
    checksums = payload["sha256"]
    tag = payload["tag"]
    header = f'''# Generated by packaging/homebrew/render-cask.py. Update the release manifest.
cask "chatgpt-community" do
  arch arm: "arm64", intel: "amd64"
  os linux: "linux"

  version "{version},{revision}"
  sha256 arm64_linux:  "{checksums['arm64']}",
         x86_64_linux: "{checksums['amd64']}"

  url "https://github.com/bruglet/chatgpt-desktop-linux/releases/download/{tag}/chatgpt-community-linux-#{{arch}}.tar.gz"
  name "ChatGPT Community"
  desc "ChatGPT with community Linux features"
  homepage "https://github.com/bruglet/chatgpt-desktop-linux"

  livecheck do
    skip "Versions require downstream patch validation on both Linux architectures"
  end

'''
    steps = '''  depends_on linux: :any

  data_home = (ENV["HOMEBREW_XDG_DATA_HOME"] || ENV.fetch("XDG_DATA_HOME", nil)).to_s
  data_home = "#{Dir.home}/.local/share" unless data_home.start_with?("/")
  desktop_file = "#{data_home}/applications/codex-desktop.desktop"

  command_wrapper "codex-desktop",
                  executable: "#{staged_path}/prepared/app/start.sh",
                  env:        { "BAMF_DESKTOP_FILE_HINT" => desktop_file }
  artifact "prepared/codex-desktop.desktop",
           target: desktop_file
  artifact "prepared/codex-desktop.png",
           target: "#{data_home}/icons/codex-desktop.png"

  preflight_steps do
    copy "prepared/app/.codex-linux/codex-desktop.png", "prepared/codex-desktop.png"
    write_file "prepared/codex-desktop.desktop", <<~DESKTOP
      [Desktop Entry]
      Type=Application
      Name=ChatGPT Community
      Comment=ChatGPT with community Linux features
      Exec="{{HOMEBREW_PREFIX}}/bin/codex-desktop" %U
      Icon=codex-desktop
      Terminal=false
      StartupWMClass=codex-desktop
      Categories=Development;
      MimeType=x-scheme-handler/codex;x-scheme-handler/codex-browser-sidebar;
      StartupNotify=true
      X-GNOME-WMClass=codex-desktop
    DESKTOP
  end

  caveats <<~EOS
    Homebrew manages updates. Close ChatGPT before upgrading or reinstalling.
    Shared ChatGPT/Codex profiles are retained on uninstall.
    The Electron sandbox requires host support for unprivileged user namespaces.
  EOS
end
'''
    return header + steps


if __name__ == "__main__":
    manifest, output = map(Path, sys.argv[1:])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(json.loads(manifest.read_text())))
